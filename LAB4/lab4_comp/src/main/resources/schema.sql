CREATE TABLE IF NOT EXISTS depots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (TRIM(name) <> ''),
    coordinates VARCHAR(100) NOT NULL CHECK (TRIM(coordinates) <> '')
);

CREATE TABLE IF NOT EXISTS drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (TRIM(name) <> ''),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (TRIM(email) <> ''),
    phone VARCHAR(30) NOT NULL CHECK (TRIM(phone) <> '')
);

CREATE TABLE IF NOT EXISTS vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE CHECK (TRIM(name) <> ''),
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    depot BIGINT NOT NULL REFERENCES depots(id) ON DELETE RESTRICT,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    driver BIGINT UNIQUE REFERENCES drivers(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (TRIM(name) <> ''),
    email VARCHAR(254) NOT NULL UNIQUE CHECK (TRIM(email) <> ''),
    phone VARCHAR(30) NOT NULL CHECK (TRIM(phone) <> ''),
    address VARCHAR(500) NOT NULL CHECK (TRIM(address) <> ''),
    coordinates VARCHAR(100) NOT NULL CHECK (TRIM(coordinates) <> '')
);

CREATE TABLE IF NOT EXISTS deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    notes TEXT,
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_vehicles_depot ON vehicles(depot);
CREATE INDEX IF NOT EXISTS idx_deliveries_customer ON deliveries(customer);

