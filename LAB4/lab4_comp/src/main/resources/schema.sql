SELECT 'Main depot', '0,0'
WHERE NOT EXISTS (SELECT 1 FROM depots);

CREATE TABLE IF NOT EXISTS scenarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (TRIM(name) <> '')
);

CREATE TABLE IF NOT EXISTS scenario_vehicles (
    scenario_id BIGINT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
    vehicle_id BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE RESTRICT,
    PRIMARY KEY (scenario_id, vehicle_id)
);

CREATE TABLE IF NOT EXISTS scenario_deliveries (
    scenario_id BIGINT NOT NULL REFERENCES scenarios(id) ON DELETE CASCADE,
    delivery_id BIGINT NOT NULL REFERENCES deliveries(id) ON DELETE RESTRICT,
    PRIMARY KEY (scenario_id, delivery_id)
);

-- Conturi comune si roluri citite de Spring Security.
CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE CHECK (TRIM(email) <> ''),
    password_hash VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN', 'CUSTOMER', 'DRIVER')),
    PRIMARY KEY (user_id, role)
);

